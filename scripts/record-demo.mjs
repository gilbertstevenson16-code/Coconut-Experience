import { chromium, expect } from '@playwright/test';
import fs from 'node:fs/promises';
const output = process.env.DEMO_OUTPUT || 'artifacts/demo';
await fs.mkdir(output, { recursive: true });
const browser = await chromium.launch({ args: ['--enable-unsafe-swiftshader', '--use-gl=angle', '--use-angle=swiftshader'] });
const context = await browser.newContext({ viewport: { width: 1440, height: 900 }, recordVideo: { dir: output, size: { width: 1440, height: 900 } } });
const page = await context.newPage();
await page.goto(process.env.BASE_URL || 'http://127.0.0.1:3145');
await page.locator('#loader').waitFor({ state: 'detached', timeout: 90000 });
await page.waitForTimeout(4000);
await page.screenshot({ path: output + '/cover.png' });
const start = Date.now();
await page.waitForTimeout(2500);
for (const y of [700, 1400, 2200, 3100, 4100]) {
  await page.mouse.wheel(0, y === 700 ? 700 : 800);
  await page.waitForTimeout(1600);
}
await page.getByRole('button', { name: 'Open menu' }).click();
await page.waitForTimeout(1000);
await page.locator('a[href="/flavours"]').filter({ hasText: 'Flavours' }).first().click();
await expect(page).toHaveURL(/\/flavours$/);
await page.waitForTimeout(4000);
await page.mouse.wheel(0, 650);
await page.waitForTimeout(2500);
await page.getByRole('button', { name: /Add .* to basket/ }).first().click();
await page.getByRole('button', { name: /Single One can/ }).first().click();
await page.getByRole('button', { name: /Open basket/ }).click();
await expect(page.getByRole('dialog', { name: 'Your basket' })).toBeVisible();
await page.waitForTimeout(2500);
await page.getByRole('button', { name: 'Close basket' }).click();
await page.getByRole('button', { name: 'Open menu' }).click();
await page.locator('a[href="/story"]').filter({ hasText: 'Story' }).first().click();
await expect(page).toHaveURL(/\/story$/);
await page.waitForTimeout(4000);
await page.mouse.wheel(0, 700);
await page.waitForTimeout(3000);
await fs.writeFile(output + '/timing.json', JSON.stringify({ demonstrationSeconds: (Date.now() - start) / 1000 }));
const video = page.video();
await context.close();
await video.saveAs(output + '/demo.webm');
await browser.close();
console.log(output);
